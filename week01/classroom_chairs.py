# Program Purpose: Calculate and display the total number of chairs 
# in a classroom given the number of rows and chairs per row.

# inputs:
rows = 6
chairs_per_row = 8

# Process:
total_chairs = rows * chairs_per_row

# outputs:
print ("=============================================")
print ("Number of rows:", rows)
print ("Chairs per row:", chairs_per_row)
print ("Calculated total chairs:", total_chairs)
print ("=============================================")
